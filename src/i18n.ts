// Simple web speech audio reader helper
export function speakText(text: string, langName: SupportedLanguage = 'Hindi') {
  if (typeof window === 'undefined' || !window.speechSynthesis) return;

  window.speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(text);

  const langCodeMap: Record<SupportedLanguage, string> = {
    English: 'en-IN',
    Hindi: 'hi-IN',
    Bengali: 'bn-IN',
    Marathi: 'mr-IN',
    Tamil: 'ta-IN',
    Telugu: 'te-IN',
    Kannada: 'kn-IN',
    Malayalam: 'ml-IN',
    Gujarati: 'gu-IN',
    Punjabi: 'pa-IN',
    Odia: 'or-IN',
    Assamese: 'as-IN',
    Urdu: 'ur-PK',
  };

  utterance.lang = langCodeMap[langName] || 'hi-IN';
  utterance.rate = 0.88; // Slightly gentle, slower pace for seniors
  utterance.pitch = 1.0;

  window.speechSynthesis.speak(utterance);
}
